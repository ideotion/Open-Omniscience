#!/usr/bin/env python3
"""Write the public appendix of catalogue keys by cross-snapshot evidence class
(catalogue_evidence.py output). Only shipped catalogue entries are listed (names and
feed addresses are public), with aggregate evidence: snapshots where the key is a source row,
snapshots that stored >=1 article, current Linux A/B/C feed-status classes.
One file per group (OUT_PREFIX-a.md, -b.md, -c.md), each under 200 KB.
Usage: python3 -I catalogue_lists.py EVIDENCE.jsonl CATALOGUE.json OUT_PREFIX"""
import json, sys
from collections import defaultdict
ev_path, cat_path, out = sys.argv[1:4]
ev = [json.loads(l) for l in open(ev_path)]
url = {}
for r in json.load(open(cat_path)):
    url.setdefault((r['domain'], r['feed_key']), r.get('rss_url') or '')
bydom = defaultdict(list)
for e in ev:
    bydom[e['domain']].append(e)
groups = {
    'A. Feed answered 200/304 on all three Linux instances; never stored an article in any of 13 snapshots':
        lambda e: e['snap_collected'] == 0 and e['snap_rows'] and set(e['linux_classes']) == {'nf:http-ok'},
    'B. No fetch recorded on any Linux instance (never fetched, or every fetch failed); never stored in any of 13 snapshots':
        lambda e: e['snap_collected'] == 0 and e['snap_rows'] and set(e['linux_classes']) == {'nf:never-checked'},
    'C. Feed-less catalogue rows that never stored an article in any of 13 snapshots':
        lambda e: e['snap_collected'] == 0 and e['snap_rows'] and set(e['linux_classes']) == {'nf:no-feed'},
}
for (title, pred), suffix in zip(groups.items(), 'abc'):
  with open(f'{out}-{suffix}.md', 'w') as w:
    w.write(f'# Catalogue appendix {suffix.upper()}: entries that never stored an article\n\n')
    w.write('Generated by `scripts/catalogue_lists.py` from the 13 snapshots described in INVENTORY.md. '
            '"sibling collects" = another catalogue feed of the same domain stored articles. '
            'These are evidence lists for a maintainer, not removal decisions (see catalogue.md §2).\n\n')
    if True:
        rows = sorted((e for e in ev if pred(e)), key=lambda e: (e['file'], e['domain']))
        w.write(f'## {title} ({len(rows)})\n\n| file | domain | name | feed | type | sibling collects |\n|---|---|---|---|---|---|\n')
        for e in rows:
            sib = any(o['snap_collected'] > 0 for o in bydom[e['domain']] if o is not e)
            name = (e['name'] or '').replace('|', '/')
            w.write(f"| {e['file'].split('/')[-1]} | {e['domain']} | {name} | {url.get((e['domain'], e['feed_key']), '')} | {e['source_type'] or ''} | {'yes' if sib else ''} |\n")
        w.write('\n')
print('written', out + '-[abc].md')
