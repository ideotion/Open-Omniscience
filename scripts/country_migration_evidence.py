#!/usr/bin/env python3
"""The generated evidence for the country-form migration (row B1, R135, R136).

Open Omniscience - Global Intelligence Platform for Investigative Journalism
Copyright (C) 2026 Ideotion. GPL-3.0-or-later.

WHAT THIS IS, AND WHAT IT IS NOT. A session cannot hold the operator's real corpus (about 130 GB against a
sandbox's tens of free GB), so the precondition of gate rows B and J, "a real pre-migration backup restored, the
duplicate-key scan at 0", cannot be met here. This script produces the next best thing and says so on every line it
writes: a corpus the app's own generator (``src/testing/corpus_gen.py``) makes in today's alpha-2 form, a backup
written by the app's own backup path, restored and scanned by the app's own code BEFORE the migration, then the
migration (``src/backup/country_migration.py``) run on the generated store with its rows-per-second measured, then
the same backup restored into the MIGRATED store and scanned again, and the P0 data-safety checks run on it. Every
figure in the report carries ``"generated": true``. It stands for the session's evidence under R135 and does NOT
stand for gate section 1c item 7, which stays an operator reading.

Each step runs in its own child process against its own data directory, because the app's database engine is a
process-wide singleton: a store is opened by exactly one process at a time, as an install's is.

    python scripts/country_migration_evidence.py --articles 20000 --work /tmp/oo-evidence --out report.json
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sqlite3
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

#: The wording every figure carries.
LABEL = (
    "GENERATED by the app's own corpus generator (src/testing/corpus_gen.py): invented articles, not any "
    "operator's corpus. It does not stand for gate section 1c item 7."
)

#: The corpus the field numbers of 2026-07-09 describe (``corpus_gen``'s own docstring): the size the migration
#: will really meet, used ONLY for the labelled extrapolation below.
FIELD_MENTIONS = 20_900_000


def _env(data_dir: Path) -> dict:
    env = {**os.environ, "OO_DATA_DIR": str(data_dir), "OO_DB_PLAINTEXT": "1", "OO_AUTOSEED": "0", "OO_NO_SCHEDULER": "1"}
    env.pop("DATABASE_URL", None)
    env.pop("OO_DB_PASSPHRASE", None)
    return env


def _child(mode: str, data_dir: Path, *args: str) -> dict:
    """Run one step in a fresh process and return the JSON line it printed last."""
    done = subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), "--child", mode, *args],
        cwd=ROOT, env=_env(data_dir), capture_output=True, text=True,
    )
    if done.returncode != 0:
        raise SystemExit(f"step {mode!r} failed:\n{done.stderr[-3000:]}")
    return json.loads(done.stdout.strip().splitlines()[-1])


# --------------------------------------------------------------------------- #
# the steps (each runs in its own process)
# --------------------------------------------------------------------------- #
def _db_path() -> Path:
    from src.paths import data_dir

    return data_dir() / "open_omniscience.db"


def _counts(path: Path) -> dict:
    con = sqlite3.connect(path)
    try:
        out = {t: con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0] for t in ("sources", "articles", "keyword_mentions", "keywords")}
        out["country_value_lengths"] = {
            f"keyword_mentions:{n}": c for n, c in con.execute("SELECT length(country), COUNT(*) FROM keyword_mentions WHERE country IS NOT NULL GROUP BY 1")
        }
        out["article_country_lengths"] = {
            f"articles:{n}": c for n, c in con.execute("SELECT length(country), COUNT(*) FROM articles WHERE country IS NOT NULL GROUP BY 1")
        }
        return out
    finally:
        con.close()


def _stamp_alembic(path: Path) -> None:
    """The artifact must carry a schema revision or the restore refuses it as pre-0.0.8 (tests/_fixture_backup_helper.py)."""
    from alembic.config import Config
    from alembic.script import ScriptDirectory

    head = ScriptDirectory.from_config(Config(str(ROOT / "alembic.ini"))).get_current_head()
    con = sqlite3.connect(path)
    con.execute("CREATE TABLE IF NOT EXISTS alembic_version (version_num VARCHAR(32) NOT NULL PRIMARY KEY)")
    con.execute("DELETE FROM alembic_version")
    con.execute("INSERT INTO alembic_version (version_num) VALUES (?)", (head,))
    con.commit()
    con.close()


def step_generate(articles: int, seed: int) -> dict:
    from src.database.country_form import writing_in
    from src.testing.corpus_gen import CorpusSpec, generate_corpus

    path = _db_path()
    t0 = time.perf_counter()
    with writing_in("alpha2"):  # the form every store made before 0.5 is in
        summary = generate_corpus(path, CorpusSpec(articles=articles, seed=seed, sources=60, mentions_per_article=78))
    _stamp_alembic(path)
    return {"generated": True, "label": LABEL, "articles": articles, "seconds": round(time.perf_counter() - t0, 1),
            "bytes": path.stat().st_size, "counts": _counts(path), "summary_keys": sorted(summary)}


def step_backup(dest: str) -> dict:
    from src.backup import artifact as art

    t0 = time.perf_counter()
    out = Path(dest)
    out.unlink(missing_ok=True)
    art.write_backup_v2(out, passphrase=None)
    return {"generated": True, "path": dest, "bytes": out.stat().st_size, "seconds": round(time.perf_counter() - t0, 1)}


def step_fresh_store(form: str) -> dict:
    """A store the APP creates (``init_db``), set to the form this step needs: alpha-3 as it is born, alpha-2 as every
    store made before 0.5 is (the marker removed)."""
    from src.config import kv_store
    from src.database import country_form as cf
    from src.database.session import engine, init_db

    init_db()
    if form == "alpha2":
        with engine.begin() as con:
            con.exec_driver_sql("DELETE FROM app_state WHERE key = ?", (cf.KEY,))
        kv_store.kv_invalidate(cf.KEY)
    return {"form": cf.store_form()}


def step_restore(backup: str) -> dict:
    from src.api.backup_v2 import restore_legacy_path
    from src.backup.country_codes import scan_country_code_duplicates
    from src.database import country_form as cf
    from src.database.session import engine

    path = _db_path()
    before = _counts(path) if path.exists() else {}
    t0 = time.perf_counter()
    report = restore_legacy_path(backup, None, trust_fetch_history=True)
    seconds = round(time.perf_counter() - t0, 1)
    with engine.connect() as con:
        scan = scan_country_code_duplicates(con.connection.dbapi_connection)
    return {"generated": True, "form": cf.store_form(), "restore_seconds": seconds, "counts_before": before,
            "counts_after": _counts(path), "scan": scan, "restore_status": report.get("status"),
            "country_codes_block": (report.get("plan") or {}).get("_country_codes")}


def step_migrate(backup_dir: str, json_out: str) -> dict:
    from src.backup import country_migration as cm

    path = _db_path()
    from src.database.session import engine

    engine.dispose()  # this process must not hold the file: the migration takes it exclusively
    events: list[dict] = []
    rep = cm.migrate(path, backup_dir=Path(backup_dir), confirm=lambda *_: True, progress=events.append)
    rows = sum(rep.rewritten.values())
    sweep = [e for e in events if e.get("phase") == "sweep"]
    Path(json_out).write_text(json.dumps(rep.__dict__, indent=1, default=str, sort_keys=True), encoding="utf-8")
    return {"generated": True, "state": rep.state, "message": rep.message, "rewritten": rep.rewritten, "rows_rewritten": rows,
            "seconds": rep.seconds, "backup_seconds": rep.backup_seconds, "sweep_seconds": rep.sweep_seconds,
            "verify_seconds": rep.verify_seconds, "rows_per_second": rep.rate_rows_per_s, "balance": rep.balance, "estimate": rep.estimate, "backup": rep.backup, "unmapped": rep.unmapped,
            "windows_committed": len(sweep), "counts_after": _counts(path)}


def step_p0(dest: str) -> dict:
    from src.monitoring.p0_validation import build_p0_report

    class _Ctx:
        stopping = False

        def set_progress(self, **_kw):
            return None

    report = build_p0_report(_Ctx(), dest_dir=Path(dest), passphrase="generated-evidence-only-not-a-secret",
                             include_newsletters=False, measure_incremental=False)
    return {"generated": True, "checks": {k: v.get("verdict") for k, v in (report.get("checks") or {}).items()}, "verdict": report.get("verdict")}


# --------------------------------------------------------------------------- #
# the driver
# --------------------------------------------------------------------------- #
def _extrapolate(mig: dict, store_bytes: int) -> dict:
    """Scale each part of the run by what it scales with. The sweep is rows, so its rate is measured as rows per second and
    applied to the field's row count; the safety copy and the proof are bytes, so their measured seconds per GB are applied to
    a field-sized store. Everything here is labelled an ESTIMATE."""
    rows, sweep = int(mig["rows_rewritten"]), float(mig["sweep_seconds"])
    rate = rows / sweep if sweep else None
    gb = store_bytes / 1e9
    per_gb = {k: (float(mig[k]) / gb if mig.get(k) and gb else None) for k in ("backup_seconds", "verify_seconds")}
    # The 2026-07-09 field store: 11.7 GB for 20.9 M mentions (corpus_gen's own anchor). The operator's is larger.
    field_gb = 11.7
    parts = {
        "sweep_seconds": FIELD_MENTIONS / rate if rate else None,
        "backup_seconds": per_gb["backup_seconds"] * field_gb if per_gb["backup_seconds"] else None,
        "verify_seconds": per_gb["verify_seconds"] * field_gb if per_gb["verify_seconds"] else None,
    }
    total = sum(v for v in parts.values() if v)
    return {
        "measured_rows": rows, "measured_sweep_seconds": round(sweep, 1), "rows_per_second": round(rate, 1) if rate else None,
        "measured_store_gb": round(gb, 3), "measured_seconds_per_gb": {k: round(v, 1) if v else None for k, v in per_gb.items()},
        "ESTIMATE_field_mentions": FIELD_MENTIONS, "ESTIMATE_field_store_gb": field_gb,
        "ESTIMATE_parts_seconds": {k: round(v) if v else None for k, v in parts.items()},
        "ESTIMATE_total_minutes": round(total / 60, 1),
        "basis": (
            f"the sweep: {rows:,} rows in {sweep:,.1f} s ({rate:,.0f} rows/s) applied to 20.9 M keyword_mentions rows; the safety copy and the "
            f"proof: seconds per GB measured on a {gb:.2f} GB generated store, applied to the 11.7 GB store of 2026-07-09. An ESTIMATE, not a "
            "measurement: a larger store has deeper indexes, a spinning disk or an encrypted file is slower, and the operator's own reading "
            "under gate section 1c item 7 replaces it."
        ),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--articles", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=1729)
    ap.add_argument("--work", type=Path, default=Path("/tmp/oo-country-evidence"))
    ap.add_argument("--out", type=Path, default=None, help="write the JSON report here")
    ap.add_argument("--keep", action="store_true", help="keep the work directory")
    ap.add_argument("--child", default=None, help=argparse.SUPPRESS)
    ap.add_argument("rest", nargs="*", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    if args.child:
        steps = {
            "generate": lambda: step_generate(int(args.rest[0]), int(args.rest[1])),
            "backup": lambda: step_backup(args.rest[0]),
            "fresh": lambda: step_fresh_store(args.rest[0]),
            "restore": lambda: step_restore(args.rest[0]),
            "migrate": lambda: step_migrate(args.rest[0], args.rest[1]),
            "p0": lambda: step_p0(args.rest[0]),
        }
        print(json.dumps(steps[args.child](), default=str))
        return 0

    work: Path = args.work
    if work.exists() and any(work.iterdir()):
        raise SystemExit(f"{work} is not empty: this script never reuses or deletes a directory it did not just make")
    work.mkdir(parents=True, exist_ok=True)
    a, b, c = work / "store-a-migrated", work / "store-b-alpha2-fresh", work / "store-c-alpha3-fresh"
    for d in (a, b, c):
        d.mkdir()
    backup = work / "pre-migration.oobackup"
    report: dict = {"generated": True, "label": LABEL, "articles": args.articles, "seed": args.seed}

    report["1_generate_alpha2_store"] = _child("generate", a, str(args.articles), str(args.seed))
    store_bytes = report["1_generate_alpha2_store"]["bytes"]
    report["2_pre_migration_backup"] = _child("backup", a, str(backup))
    # BEFORE the migration: the backup restored into a store of today's form, and scanned.
    report["3a_restore_before_into_alpha2_store"] = {**_child("fresh", b, "alpha2"), **_child("restore", b, str(backup))}
    report["3b_restore_into_fresh_alpha3_store"] = {**_child("fresh", c, "alpha3"), **_child("restore", c, str(backup))}
    # THE MIGRATION, on the generated store.
    mig = _child("migrate", a, str(work / "backups"), str(work / "migration-report.json"))
    report["4_migration"] = mig
    if mig.get("rows_rewritten") and mig.get("sweep_seconds"):
        report["4_migration"]["extrapolation"] = _extrapolate(mig, store_bytes)
    # AFTER: the same pre-migration backup into the migrated store, scanned again, then the P0 checks.
    report["5_restore_after_into_migrated_store"] = _child("restore", a, str(backup))
    report["6_p0_checks_on_migrated_store"] = _child("p0", a, str(work / "p0"))

    after = report["5_restore_after_into_migrated_store"]
    def dup(r: dict):
        return (r.get("scan") or {}).get("duplicates")

    report["summary"] = {
        "duplicates_before_alpha2": dup(report["3a_restore_before_into_alpha2_store"]),
        "duplicates_fresh_alpha3": dup(report["3b_restore_into_fresh_alpha3_store"]),
        "duplicates_after_migration": dup(after),
        "articles_unchanged_by_restore_after": after["counts_before"].get("articles") == after["counts_after"].get("articles"),
        "mentions_unchanged_by_restore_after": after["counts_before"].get("keyword_mentions") == after["counts_after"].get("keyword_mentions"),
        "p0_checks": report["6_p0_checks_on_migrated_store"].get("checks"),
    }
    text = json.dumps(report, indent=1, default=str, sort_keys=True)
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    print(text)
    if not args.keep:
        shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
